import { loadLetterhead, type Db } from '../../email/letterhead';

export interface DocumentHeader {
  organisationName: string;
  logo: { content: Buffer; mime: string; box: { width: number; height: number } } | null;
  title: string;
  projectName: string;
  reportType: string;
  versionNo: number;
  /** `yyyy-mm-dd`, or an ISO timestamp (read as a UTC+8 day). */
  issueDate: string;
  aiAssisted: boolean;
  generatedAt: Date;
}

const MONTHS = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
const UTC8_MS = 8 * 60 * 60 * 1000;

function parts(d: Date): { day: number; month: string; year: number; hh: string; mm: string } {
  const s = new Date(d.getTime() + UTC8_MS);
  return { day: s.getUTCDate(), month: MONTHS[s.getUTCMonth()], year: s.getUTCFullYear(), hh: String(s.getUTCHours()).padStart(2, '0'), mm: String(s.getUTCMinutes()).padStart(2, '0') };
}

/** `d MMMM yyyy` in UTC+8, English month names. */
export function formatDate(d: Date): string {
  const p = parts(d);
  return `${p.day} ${p.month} ${p.year}`;
}

/** `d MMMM yyyy HH:mm` in UTC+8. */
export function formatDateTime(d: Date): string {
  const p = parts(d);
  return `${p.day} ${p.month} ${p.year} ${p.hh}:${p.mm}`;
}

function formatIssueDate(v: string): string {
  const m = /^(\d{4})-(\d{2})-(\d{2})$/.exec(v);
  if (m) return `${Number(m[3])} ${MONTHS[Number(m[2]) - 1] ?? m[2]} ${m[1]}`;
  const d = new Date(v);
  return Number.isNaN(d.getTime()) ? v : formatDate(d);
}

/** The header every generated file carries (spec 6.2). A filed file is never changed, so it always reads "Draft — not approved". */
export function headerLines(h: DocumentHeader): string[] {
  const lines = [h.title, `${h.projectName} · ${h.reportType} · Version ${h.versionNo} · Issued ${formatIssueDate(h.issueDate)}`, 'Draft — not approved'];
  if (h.aiAssisted) lines.push('Prepared with AI assistance; facts from Kainow records');
  lines.push(`Generated by Kainow on ${formatDateTime(h.generatedAt)} UTC+8`);
  return lines;
}

export type HeaderOptions = Omit<DocumentHeader, 'organisationName' | 'logo' | 'generatedAt'> & { generatedAt?: Date };

/** Adds the letterhead (organisation name and wide logo; Kainow's own until the organisation registers, D71). */
export async function loadDocumentHeader(db: Db, opts: HeaderOptions): Promise<DocumentHeader> {
  const lh = await loadLetterhead(db, 'report');
  return { ...opts, generatedAt: opts.generatedAt ?? new Date(), organisationName: lh.name, logo: lh.logo };
}
