/**
 * The event catalogue (dashboards spec 10, A12, R17): every action Kainow records, as documentation for the Definitions
 * page. It changes nothing about how events are written. `name` is the stored value: the `audit_events.action`, or the
 * kind, action or outcome of a per-domain event table. `measurements` names the analytics measures read from it. A
 * completeness test (catalogue.db.test.ts) checks this list against every `writeAudit` call and every event-table CHECK.
 */

export type CatalogueEntry = {
  name: string;
  table: string;
  version: string;
  area: string;
  meaning: string;
  actor: string;
  subject: string;
  measurements: string[];
};

const VERSION = '1';

/** Entries for one table and area: `(name, meaning, measurements?)` each. */
function group(table: string, area: string, actor: string, subject: string, entries: Array<[string, string, string[]?]>): CatalogueEntry[] {
  return entries.map(([name, meaning, measurements]) => ({ name, table, version: VERSION, area, meaning, actor, subject, measurements: measurements ?? [] }));
}
const audit = (area: string, actor: string, subject: string, entries: Array<[string, string, string[]?]>) => group('audit_events', area, actor, subject, entries);

